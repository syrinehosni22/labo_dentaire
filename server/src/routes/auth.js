// A user who must change their password can only reach their own account endpoints
router.use((req, res, next) => {
  if (!req.user.must_change_password) return next();
  if (req.path === '/auth/me' || req.path === '/auth/change-password' || req.path === '/settings') return next();
  return res.status(403).json({ error: 'Vous devez choisir un nouveau mot de passe avant de continuer.', code: 'password_change_required' });
});

