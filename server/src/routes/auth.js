const SELF_RESET_MINUTES = 60;          // link sent by e-mail
const ADMIN_RESET_HOURS = 24;           // link generated by an administrator

/* ---------------- rate limiting (in memory) ---------------- */
function limiter({ max, windowMs, blockMs }) {
  const hits = new Map();
  return (key) => {
    const now = Date.now();
    const h = hits.get(key) || { n: 0, start: now, until: 0 };
    if (h.until > now) return false;
    if (now - h.start > windowMs) { h.n = 0; h.start = now; }
    h.n += 1;
    if (h.n > max) { h.until = now + blockMs; h.n = 0; hits.set(key, h); return false; }
    hits.set(key, h);
    return true;
  };
}
const loginFailures = new Map();
const forgotLimit = limiter({ max: 5, windowMs: 15 * 60e3, blockMs: 15 * 60e3 });
const resetLimit = limiter({ max: 20, windowMs: 15 * 60e3, blockMs: 15 * 60e3 });

/* ---------------- helpers ---------------- */
const hashToken = (t) => crypto.createHash('sha256').update(t).digest('hex');

const invalidateResets = (userId) => col('password_resets').updateMany({ user_id: userId, used_at: null }, { $set: { used_at: nowStamp() } });

async function setPassword(userId, password, { mustChange = false } = {}) {
  await col('users').updateOne({ _id: userId }, {
    $set: { password_hash: bcrypt.hashSync(password, 10), must_change_password: !!mustChange, password_changed_at: nowStamp() },
    $inc: { token_version: 1 },
  });
  // any pending reset link becomes useless once the password changes
  await invalidateResets(userId);
}

async function createResetToken(user, origin, createdBy) {
  await invalidateResets(user.id);
  const token = crypto.randomBytes(32).toString('base64url');
  const ms = origin === 'admin' ? ADMIN_RESET_HOURS * 3600e3 : SELF_RESET_MINUTES * 60e3;
  const expires = new Date(Date.now() + ms);
  await insert('password_resets', { user_id: user.id, token_hash: hashToken(token), expires_at: expires.toISOString(), used_at: null, origin, created_by: createdBy || null });
  return { token, expires };
}

async function findValidReset(token) {
  if (typeof token !== 'string' || token.length < 20) return null;
  const r = out(await col('password_resets').findOne({ token_hash: hashToken(token) }));
  if (!r || r.used_at || new Date(r.expires_at) < new Date()) return null;
  const u = await findUser(r.user_id);
  if (!u || !u.active) return null;
  return { ...r, email: u.email, name: u.name };
}

const userByEmail = async (email) => out(await col('users').findOne({ email_key: keyOf(email) }));

// Public URL of the app, for links in e-mails. Never derived from Host/Origin headers when a
// configured address exists: otherwise a forged request could e-mail a link to another site.
async function appUrl(req) {
  // CLIENT_URL = where the React interface runs (dev: Vite on :5173); otherwise the public APP_URL
  const configured = process.env.CLIENT_URL || process.env.APP_URL || ((await getSetting('lab')) || {}).app_url;
  if (configured) return String(configured).replace(/\/$/, '');
  if (process.env.NODE_ENV === 'production') console.warn("[sécurité] Renseignez l'adresse publique de l'application (Paramètres → Laboratoire ou APP_URL) pour les liens envoyés par e-mail.");
  const origin = req.headers.origin;
  if (origin && /^https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(origin)) return origin;   // dev server on :5173
  return `${req.protocol}://${req.headers.host}`;
}

const maskEmail = (e) => e.replace(/^(.)(.*)(.@.*)$/, (_, a, mid, b) => a + '•'.repeat(Math.min(mid.length, 6)) + b);

function resetEmail(user, link, minutes, labName) {
  const subject = `Réinitialisation de votre mot de passe — ${labName}`;
  const text = `Bonjour ${user.name},

Une demande de réinitialisation du mot de passe de votre compte ${labName} a été faite.

Pour choisir un nouveau mot de passe, ouvrez ce lien (valable ${minutes >= 120 ? `${minutes / 60} heures` : `${minutes} minutes`}, utilisable une seule fois) :
${link}

Si vous n'êtes pas à l'origine de cette demande, ignorez ce message : votre mot de passe actuel reste inchangé.`;
  const html = `<div style="font-family:Arial,sans-serif;font-size:15px;color:#1e2a2f;max-width:520px">
<p>Bonjour ${user.name.replace(/</g, '&lt;')},</p>
<p>Une demande de réinitialisation du mot de passe de votre compte <strong>${labName.replace(/</g, '&lt;')}</strong> a été faite.</p>
<p><a href="${link}" style="display:inline-block;background:#b03552;color:#fff;padding:12px 20px;border-radius:6px;text-decoration:none;font-weight:bold">Choisir un nouveau mot de passe</a></p>
<p style="color:#5e6b70;font-size:13px">Ce lien est valable ${minutes >= 120 ? `${minutes / 60} heures` : `${minutes} minutes`} et ne peut être utilisé qu'une seule fois.<br>Si vous n'êtes pas à l'origine de cette demande, ignorez ce message : votre mot de passe actuel reste inchangé.</p>
</div>`;
  return { subject, text, html };
}

const labName = async () => ((await getSetting('lab')) || {}).name || 'Laboratoire dentaire';

/* ---------------- public routes ---------------- */
router.post('/auth/login', async (req, res) => {
  const { email, password } = req.body || {};
  const key = `${req.ip}:${String(email || '').toLowerCase()}`;
  const a = loginFailures.get(key) || { n: 0, until: 0 };
  if (a.until > Date.now()) return res.status(429).json({ error: 'Trop de tentatives. Réessayez dans quelques minutes ou réinitialisez votre mot de passe.' });
  const u = await userByEmail(String(email || '').trim());
  if (!u || !u.active || !bcrypt.compareSync(String(password || ''), u.password_hash)) {
    a.n += 1; if (a.n >= 5) { a.until = Date.now() + 5 * 60 * 1000; a.n = 0; }
    loginFailures.set(key, a);
    if (u) { req.user = u; audit(req, 'échec de connexion', 'user', u.id); }
    return res.status(401).json({ error: 'E-mail ou mot de passe incorrect.' });
  }
  loginFailures.delete(key);
  req.user = u; audit(req, 'connexion', 'user', u.id);
  res.json({ token: sign(u), user: publicUser(u) });
});

// Step 1 — "Mot de passe oublié": same answer whether or not the account exists
router.post('/auth/forgot', async (req, res) => {
  const email = String(req.body?.email || '').trim();
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) throw bad('Saisissez une adresse e-mail valide.');
  if (!forgotLimit(`${req.ip}`) || !forgotLimit(`mail:${email.toLowerCase()}`)) {
    return res.status(429).json({ error: 'Trop de demandes. Réessayez dans 15 minutes.' });
  }
  const generic = { ok: true, message: "Si un compte actif correspond à cette adresse, un e-mail contenant un lien de réinitialisation vient d'être envoyé." };
  const u = await userByEmail(email);
  if (!u || !u.active) return res.json(generic);

  req.user = u;
  const { token } = await createResetToken(u, 'email');
  const link = `${await appUrl(req)}/reinitialiser/${token}`;
  const result = await sendMail({ to: u.email, ...resetEmail(u, link, SELF_RESET_MINUTES, await labName()) });
  audit(req, 'demande de réinitialisation du mot de passe', 'user', u.id, { email_envoye: result.sent, ...(result.sent ? {} : { raison: result.reason }) });

  if (!result.sent) {
    // No e-mail possible: warn administrators in the platform so they can issue a link themselves
    const { notifyOnce } = require('../services/notifier');
    const admins = await col('users').find({ active: true, role: 'admin' }, { projection: { _id: 1 } }).toArray();
    for (const ad of admins) {
      await notifyOnce({
        user_id: ad._id, request_id: null, type: 'password_reset', due_at: null, overdue: false,
        title: `Mot de passe oublié — ${u.name}`,
        message: `${u.name} (${u.email}) a demandé à réinitialiser son mot de passe, mais l'e-mail n'a pas pu être envoyé. Générez un lien depuis Utilisateurs.`,
        dedup_key: `pwreset:${u.id}:${new Date().toISOString().slice(0, 13)}`,
      });
    }
    if (process.env.NODE_ENV !== 'production') console.log(`[dev] Lien de réinitialisation pour ${u.email} : ${link}`);
  }
  res.json(generic);
});

// Step 2 — check the link before showing the form
router.get('/auth/reset/:token', async (req, res) => {
  if (!resetLimit(req.ip)) return res.status(429).json({ error: 'Trop de tentatives. Réessayez plus tard.' });
  const r = await findValidReset(req.params.token);
  if (!r) return res.status(400).json({ error: 'Ce lien de réinitialisation est invalide, a déjà été utilisé ou a expiré.', code: 'invalid_token' });
  res.json({ email: maskEmail(r.email), name: r.name.split(' ')[0], expires_at: r.expires_at });
});

// Step 3 — set the new password
router.post('/auth/reset', async (req, res) => {
  if (!resetLimit(req.ip)) return res.status(429).json({ error: 'Trop de tentatives. Réessayez plus tard.' });
  const { token, password } = req.body || {};
  // single use: the link is consumed atomically before anything else (two parallel submits cannot both succeed)
  const r = await findValidReset(token);
  if (!r) return res.status(400).json({ error: 'Ce lien de réinitialisation est invalide, a déjà été utilisé ou a expiré.', code: 'invalid_token' });
  const u = await findUser(r.user_id);
  const problem = passwordProblem(password, u);
  if (problem) throw bad(problem);
  if (bcrypt.compareSync(password, u.password_hash)) throw bad("Choisissez un mot de passe différent de l'ancien.");
  const claimed = await col('password_resets').updateOne({ _id: r.id, used_at: null }, { $set: { used_at: nowStamp() } });
  if (!claimed.modifiedCount) return res.status(400).json({ error: 'Ce lien de réinitialisation a déjà été utilisé.', code: 'invalid_token' });
  await setPassword(u.id, password);
  loginFailures.forEach((_, k) => { if (k.endsWith(`:${u.email.toLowerCase()}`)) loginFailures.delete(k); });
  req.user = u; audit(req, 'mot de passe réinitialisé', 'user', u.id, { via: r.origin === 'admin' ? 'lien administrateur' : 'e-mail' });
  sendMail({ to: u.email, subject: `Votre mot de passe a été modifié — ${await labName()}`, text: `Bonjour ${u.name},\n\nLe mot de passe de votre compte vient d'être modifié. Si vous n'êtes pas à l'origine de ce changement, contactez immédiatement l'administrateur du laboratoire.` }).catch(() => {});
  res.json({ ok: true, email: u.email });
});

