// Change own password (also used for the forced change at first login). Returns a fresh token:
// other sessions of this user are signed out.
router.post('/auth/change-password', async (req, res) => {
  const { current_password, new_password } = req.body || {};
  const u = req.user;
  if (!bcrypt.compareSync(String(current_password || ''), u.password_hash)) throw bad('Mot de passe actuel incorrect.');
  const problem = passwordProblem(new_password, u);
  if (problem) throw bad(problem);
  if (bcrypt.compareSync(new_password, u.password_hash)) throw bad("Choisissez un mot de passe différent de l'actuel.");
  await setPassword(u.id, new_password);
  audit(req, 'changement de mot de passe', 'user', u.id);
  const fresh = await findUser(u.id);
  res.json({ token: sign(fresh), user: publicUser(fresh) });
});

// Own profile: phone, notification prefs, name
router.put('/auth/me', async (req, res) => {
  const { phone, notif_prefs, name } = req.body || {};
  const u = req.user;
  if (req.body?.new_password) throw bad('Utilisez « Changer le mot de passe ».');
  if (phone !== undefined && phone && !/^\+?[0-9 .-]{6,20}$/.test(phone)) throw bad('Numéro de téléphone invalide.');
  const prefs = { ...defaultPrefs(), ...obj(u.notif_prefs, {}), ...(notif_prefs || {}) };
  await col('users').updateOne({ _id: u.id }, { $set: { phone: phone !== undefined ? (phone || null) : (u.phone || null), notif_prefs: prefs, name: name || u.name } });
  res.json(publicUser(await findUser(u.id)));
});

