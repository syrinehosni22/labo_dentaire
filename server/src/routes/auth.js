function validateUserBody(b, isNew) {
  if (!b.name?.trim()) throw bad('Le nom est obligatoire.');
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(b.email || '')) throw bad('Adresse e-mail invalide.');
  if (!ROLE_LABELS[b.role]) throw bad('Profil invalide.');
  if (isNew || b.password) { const p = passwordProblem(b.password, b); if (p) throw bad(p); }
}

router.post('/users', requirePerm('users_manage'), async (req, res) => {
  const b = req.body; validateUserBody(b, true);
  if (await userByEmail(b.email)) throw conflict('Un utilisateur utilise déjà cette adresse e-mail.');
  // a password chosen by the administrator is temporary: the user changes it at first login
  const u = await insert('users', {
    email: b.email.trim(), email_key: keyOf(b.email), password_hash: bcrypt.hashSync(b.password, 10), name: b.name.trim(), role: b.role,
    permissions: b.permission_overrides || {}, phone: b.phone || null, notif_prefs: defaultPrefs(), active: true, token_version: 0,
    must_change_password: b.must_change_password !== false, password_changed_at: nowStamp(),
  });
  audit(req, 'création utilisateur', 'user', u.id, { email: b.email, role: b.role });
  res.status(201).json(publicUser(u));
});

router.put('/users/:id', requirePerm('users_manage'), async (req, res) => {
  const u = await findUser(toId(req.params.id));
  if (!u) throw notFound();
  const b = { ...publicUser(u), ...req.body }; validateUserBody(b, false);
  const same = await userByEmail(b.email);
  if (same && same.id !== u.id) throw conflict('Un utilisateur utilise déjà cette adresse e-mail.');
  if (u.id === req.user.id && (b.role !== 'admin' || b.active === false)) throw bad('Vous ne pouvez pas retirer vos propres droits administrateur.');
  if (u.role === 'admin' && (b.role !== 'admin' || b.active === false)) {
    const admins = await col('users').countDocuments({ role: 'admin', active: true });
    if (admins <= 1) throw bad('Il doit rester au moins un administrateur actif.');
  }
  await col('users').updateOne({ _id: u.id }, { $set: {
    email: b.email.trim(), email_key: keyOf(b.email), name: b.name.trim(), role: b.role,
    permissions: b.permission_overrides || {}, phone: b.phone || null, active: !!b.active,
  } });
  if (req.body.password) await setPassword(u.id, req.body.password, { mustChange: req.body.must_change_password !== false && u.id !== req.user.id });
  // deactivating an account ends its sessions
  if (u.active && !b.active) await col('users').updateOne({ _id: u.id }, { $inc: { token_version: 1 } });
  audit(req, req.body.password ? 'modification utilisateur (nouveau mot de passe)' : 'modification utilisateur', 'user', u.id, { role: b.role, active: b.active });
  res.json(publicUser(await findUser(u.id)));
});

// Administrator issues a reset link (works even without SMTP: the link is shown to copy and pass on)
router.post('/users/:id/reset-link', requirePerm('users_manage'), async (req, res) => {
  const u = await findUser(toId(req.params.id));
  if (!u) throw notFound();
  if (!u.active) throw bad("Ce compte est désactivé : réactivez-le avant d'envoyer un lien.");
  const { token, expires } = await createResetToken(u, 'admin', req.user.id);
  const link = `${await appUrl(req)}/reinitialiser/${token}`;
  let emailed = { sent: false, reason: null };
  if (req.body?.send_email) emailed = await sendMail({ to: u.email, ...resetEmail(u, link, ADMIN_RESET_HOURS * 60, await labName()) });
  audit(req, 'lien de réinitialisation généré', 'user', u.id, { envoye_par_email: emailed.sent });
  res.json({ link, expires_at: expires.toISOString(), emailed: emailed.sent, email_error: emailed.reason });
});

router.post('/users/:id/revoke-sessions', requirePerm('users_manage'), async (req, res) => {
  const u = await findUser(toId(req.params.id));
  if (!u) throw notFound();
  await col('users').updateOne({ _id: u.id }, { $inc: { token_version: 1 } });
  await invalidateResets(u.id);
  audit(req, 'déconnexion forcée', 'user', u.id);
  res.json({ ok: true });
});

